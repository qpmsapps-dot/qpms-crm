  static CrashLogLevel classify(
    String action, {
    Object? error,
    StackTrace? stackTrace,
    CrashLogLevel? level,
  }) {
    final name = action.toUpperCase();
    final criticalFailure = RegExp(
      r'FAILED|FAILURE|ERROR|EXCEPTION|DENIED|TIMEOUT|NOT_FOUND|NOT_CONFIRMED|UNAVAILABLE|INVALID|MISMATCH|PENDING',
    );
    final corruption = RegExp(
      r'SQLITE_CORRUPT|DATABASE DISK IMAGE IS MALFORMED|DATABASE.*CORRUPT',
    );
    final failure = RegExp(
      r'FAILED|FAILURE|ERROR|EXCEPTION|DENIED|DISABLED|MISSING|TIMEOUT|BLOCKED|NOT_FOUND|NOT_CONFIRMED|PENDING|UNAVAILABLE|INVALID|REQUIRED|MISMATCH|WARNING',
    );
    if (corruption.hasMatch(error?.toString().toUpperCase() ?? '') ||
        name.contains('FATAL') ||
        name.contains('DATABASE_CORRUPTION') ||
        name.contains('UNRECOVERABLE') ||
        name.endsWith('_CRASH') ||
        {
          'BOOTSTRAP_FAILED',
          'SUPABASE_INITIALIZE_FAILED',
          'BACKGROUND_SUPABASE_INIT_FAILED',
          'PLATFORM_ERROR',
          'ZONE_ERROR',
        }.contains(name) ||
        name.contains('END_DAY') &&
            (criticalFailure.hasMatch(name) ||
                error is Exception ||
                error is Error ||
                stackTrace != null)) {
      return CrashLogLevel.critical;
    }
    if (level == CrashLogLevel.critical) return CrashLogLevel.critical;
    // Caller-supplied diagnostic levels cannot demote real failures.
    if (error is Exception || error is Error || stackTrace != null) {
      return CrashLogLevel.error;
    }
    if (level == CrashLogLevel.error) return CrashLogLevel.error;
    if (diagnostics.contains(name) || rejections.contains(name)) {
      return CrashLogLevel.diagnostic;
    }
    if (failure.hasMatch(name)) return CrashLogLevel.error;
    if (level == CrashLogLevel.diagnostic ||
        diagnostics.contains(name) ||
        rejections.contains(name)) {
      return CrashLogLevel.diagnostic;
    }
    return CrashLogLevel.error;
  }
